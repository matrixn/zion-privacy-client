    {
        $locale = strtolower((string) get_user_locale());

        return $locale === 'ro' || str_starts_with($locale, 'ro_') || str_starts_with($locale, 'ro-');
    }

    public static function locale(): string
    {
        return self::isRomanian() ? 'ro_RO' : 'en_US';
